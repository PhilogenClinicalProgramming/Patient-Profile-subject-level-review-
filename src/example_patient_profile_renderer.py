#!/usr/bin/env python
"""
Example public Patient Profile renderer.

This script illustrates how standardized intermediate Patient Profile tables can be
converted into a simple subject-level HTML report. It is intentionally minimal and
does not reproduce any production dashboard, internal PDF template, proprietary
layout, or study-specific clinical logic.

Input
-----
A folder containing standardized CSV tables generated by:
    common_tables_generator_patient_profile.py

Typical tables:
    subject_master.csv
    visit_status.csv
    treatment_administration.csv
    adverse_events.csv
    laboratory_measurements.csv
    tumor_assessments.csv
    overall_tumor_response.csv
    end_of_study_status.csv
    overall_survival.csv
    patient_status_summary.csv

Usage
-----
python example_patient_profile_renderer.py \
  --tables examples/outputs/synthetic_pheedit_common_tables \
  --subject SUBJ-001 \
  --out examples/outputs/patient_profile_SUBJ-001.html
"""

from __future__ import annotations

import argparse
import html
from pathlib import Path
from typing import Any

import pandas as pd


SECTION_TABLES = [
    ("Subject summary", "subject_master"),
    ("Patient status", "patient_status_summary"),
    ("Visit overview", "visit_status"),
    ("Treatment administration", "treatment_administration"),
    ("Adverse events", "adverse_events"),
    ("Laboratory measurements", "laboratory_measurements"),
    ("Tumor assessments", "tumor_assessments"),
    ("Overall tumor response", "overall_tumor_response"),
    ("End of study", "end_of_study_status"),
    ("Overall survival", "overall_survival"),
]


def load_table(tables_dir: Path, table_name: str) -> pd.DataFrame:
    path = tables_dir / f"{table_name}.csv"
    if not path.exists():
        return pd.DataFrame()
    return pd.read_csv(path, low_memory=False)


def clean_cell(value: Any) -> str:
    if pd.isna(value):
        return ""
    return html.escape(str(value))


def subject_filter(df: pd.DataFrame, subject_id: str) -> pd.DataFrame:
    if df.empty or "subject_id" not in df.columns:
        return df
    return df.loc[df["subject_id"].astype(str).str.strip().eq(str(subject_id).strip())].copy()


def limit_columns(df: pd.DataFrame, table_name: str) -> pd.DataFrame:
    preferred = {
        "subject_master": [
            "subject_id", "site_id", "country", "treatment_group", "study_part",
            "sex", "age", "race", "ethnicity", "enrollment_date",
        ],
        "patient_status_summary": [
            "subject_id", "patient_status", "first_dose_date", "last_dose_date",
            "end_of_treatment_date", "last_contact_date", "death_date",
        ],
        "visit_status": [
            "visit_name", "visit_order", "visit_date", "visit_status",
            "expected_flag", "performed_flag", "optional_flag", "not_done_reason",
        ],
        "treatment_administration": [
            "visit_name", "drug_name", "administration_date", "dose", "dose_unit",
            "administered_flag", "reason_not_administered", "dose_modified_flag",
        ],
        "adverse_events": [
            "ae_id", "ae_term", "start_date", "end_date", "ongoing_flag", "grade",
            "serious_flag", "relatedness_as_recorded", "outcome",
        ],
        "laboratory_measurements": [
            "visit_name", "assessment_date", "panel", "parameter", "result_value",
            "result_unit", "normal_low", "normal_high", "abnormal_flag",
            "clinically_significant_flag",
        ],
        "tumor_assessments": [
            "visit_name", "assessment_date", "lesion_type", "lesion_id", "location",
            "measurement_value", "measurement_unit", "response", "new_lesion_flag",
        ],
        "overall_tumor_response": [
            "visit_name", "assessment_date", "target_response", "non_target_response",
            "new_lesion_progression", "overall_response", "reason_not_assessed",
        ],
        "end_of_study_status": [
            "treatment_completed_flag", "reason_treatment_not_completed",
            "maintenance_completed_flag", "followup_completed_flag", "end_of_study_date",
        ],
        "overall_survival": [
            "last_contact_date", "death_date", "vital_status", "reason",
        ],
    }
    cols = [c for c in preferred.get(table_name, list(df.columns)) if c in df.columns]
    return df[cols] if cols else df


def sort_for_display(df: pd.DataFrame) -> pd.DataFrame:
    sort_cols = [c for c in ["visit_order", "visit_date", "assessment_date", "start_date", "ae_id"] if c in df.columns]
    if sort_cols:
        return df.sort_values(sort_cols, na_position="last")
    return df


def dataframe_to_html_table(df: pd.DataFrame, *, max_rows: int = 80) -> str:
    if df.empty:
        return "<p class='empty'>No records available for this subject.</p>"

    truncated = len(df) > max_rows
    view = df.head(max_rows).copy()

    header = "".join(f"<th>{html.escape(str(c))}</th>" for c in view.columns)
    body_rows = []
    for _, row in view.iterrows():
        cells = "".join(f"<td>{clean_cell(row[c])}</td>" for c in view.columns)
        body_rows.append(f"<tr>{cells}</tr>")

    note = f"<p class='note'>Showing first {max_rows} of {len(df)} records.</p>" if truncated else ""
    return f"{note}<table><thead><tr>{header}</tr></thead><tbody>{''.join(body_rows)}</tbody></table>"


def render_profile(tables_dir: Path, subject_id: str, out_file: Path) -> None:
    sections_html = []
    available_subjects = set()

    subject_master = load_table(tables_dir, "subject_master")
    if not subject_master.empty and "subject_id" in subject_master.columns:
        available_subjects = set(subject_master["subject_id"].dropna().astype(str).str.strip())

    if available_subjects and str(subject_id).strip() not in available_subjects:
        raise ValueError(
            f"Subject '{subject_id}' not found in subject_master.csv. "
            f"Available examples: {sorted(available_subjects)[:10]}"
        )

    for title, table_name in SECTION_TABLES:
        df = load_table(tables_dir, table_name)
        df = subject_filter(df, subject_id)
        df = limit_columns(df, table_name)
        df = sort_for_display(df)
        sections_html.append(
            f"<section><h2>{html.escape(title)}</h2>{dataframe_to_html_table(df)}</section>"
        )

    html_doc = f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>Patient Profile - {html.escape(subject_id)}</title>
<style>
body {{
  font-family: Arial, Helvetica, sans-serif;
  margin: 2rem;
  color: #222;
  line-height: 1.35;
}}
h1 {{
  border-bottom: 2px solid #222;
  padding-bottom: 0.4rem;
}}
h2 {{
  margin-top: 2rem;
  border-bottom: 1px solid #ccc;
  padding-bottom: 0.25rem;
}}
table {{
  border-collapse: collapse;
  width: 100%;
  font-size: 0.85rem;
  margin-top: 0.5rem;
}}
th, td {{
  border: 1px solid #ddd;
  padding: 0.35rem 0.45rem;
  vertical-align: top;
}}
th {{
  background: #f2f2f2;
  text-align: left;
}}
.empty, .note {{
  color: #666;
  font-style: italic;
}}
.disclaimer {{
  padding: 0.75rem;
  background: #f7f7f7;
  border-left: 4px solid #999;
}}
</style>
</head>
<body>
<h1>Patient Profile</h1>
<p><strong>Subject:</strong> {html.escape(subject_id)}</p>
<p class="disclaimer">
This is a simplified public example renderer based on standardized intermediate tables.
It is not a production dashboard, not a clinical review system, and not a validated PDF template.
</p>
{''.join(sections_html)}
</body>
</html>
"""
    out_file.parent.mkdir(parents=True, exist_ok=True)
    out_file.write_text(html_doc, encoding="utf-8")


def main() -> None:
    parser = argparse.ArgumentParser(description="Render a simplified public Patient Profile HTML report.")
    parser.add_argument("--tables", required=True, help="Folder containing standardized common table CSV files.")
    parser.add_argument("--subject", required=True, help="Subject identifier to render.")
    parser.add_argument("--out", required=True, help="Output HTML file.")
    args = parser.parse_args()

    render_profile(Path(args.tables), args.subject, Path(args.out))
    print(f"[OK] Patient Profile HTML written to: {args.out}")


if __name__ == "__main__":
    main()
